-- 1. TABELAS AUXILIARES E LOCALIZAÇÃO
IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_ESTADO' AND xtype='U')
BEGIN
    CREATE TABLE TB_ESTADO (
        ID_ESTADO INT PRIMARY KEY,
        NOME VARCHAR(60) NOT NULL,
        UF CHAR(2) NOT NULL CONSTRAINT UN_ESTADO_UF UNIQUE
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_CIDADE' AND xtype='U')
