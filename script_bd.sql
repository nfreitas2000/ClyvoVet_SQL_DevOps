-- 2. TABELAS DE USUÁRIOS E PERFIS
IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_USUARIO' AND xtype='U')
BEGIN
    CREATE TABLE TB_USUARIO (
        ID_USUARIO INT PRIMARY KEY,
        EMAIL VARCHAR(80) NOT NULL CONSTRAINT UN_USUARIO_EMAIL UNIQUE,
        SENHA VARCHAR(100) NOT NULL,
        TIPO_USER VARCHAR(35) NOT NULL CONSTRAINT CK_USUARIO_TIPO CHECK (TIPO_USER IN ('TUTOR','VETERINARIO')),
        DATA_CRIACAO DATETIME2 NOT NULL DEFAULT SYSDATETIMEOFFSET() AT TIME ZONE 'E. South America Standard Time'
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_TUTOR' AND xtype='U')
BEGIN
    CREATE TABLE TB_TUTOR (
        ID_TUTOR INT PRIMARY KEY,
        NOME_TUTOR VARCHAR(100) NOT NULL,
        CPF VARCHAR(14) NOT NULL CONSTRAINT UN_TUTOR_CPF UNIQUE,
        TELEFONE VARCHAR(15) NOT NULL,
        DT_NASCIMENTO DATE NOT NULL,
        ID_USUARIO INT NOT NULL CONSTRAINT FK_TUTOR_USUARIO REFERENCES TB_USUARIO(ID_USUARIO)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_VETERINARIO' AND xtype='U')
BEGIN
    CREATE TABLE TB_VETERINARIO (
        ID_VETERINARIO INT PRIMARY KEY,
        NOME VARCHAR(100) NOT NULL,
        CRMV VARCHAR(14) NOT NULL CONSTRAINT UN_VETERINARIO_CRMV UNIQUE,
        TELEFONE VARCHAR(15) NOT NULL,
        ESPECIALIDADE VARCHAR(100) NOT NULL,
        DT_NASCIMENTO DATE NOT NULL,
        ID_USUARIO INT NOT NULL CONSTRAINT FK_VETERINARIO_USUARIO REFERENCES TB_USUARIO(ID_USUARIO)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_ENDERECO' AND xtype='U')
BEGIN
    CREATE TABLE TB_ENDERECO (
        ID_ENDERECO INT PRIMARY KEY,
        LOGRADOURO VARCHAR(120) NOT NULL,
        NUMERO VARCHAR(10) NOT NULL,
        COMPLEMENTO VARCHAR(50) NOT NULL,
        CEP VARCHAR(9) NOT NULL,
        LATITUDE DECIMAL(10,8) NOT NULL,
        LONGITUDE DECIMAL(11,8) NOT NULL,
        ID_USUARIO INT NOT NULL CONSTRAINT FK_ENDERECO_USUARIO REFERENCES TB_USUARIO(ID_USUARIO),
        ID_BAIRRO INT NOT NULL CONSTRAINT FK_ENDERECO_BAIRRO REFERENCES TB_BAIRRO(ID_BAIRRO)
    );
END;

-- 3. DOMÍNIO VETERINÁRIO (PETS E RAÇAS)
IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_ESPECIE' AND xtype='U')
BEGIN
    CREATE TABLE TB_ESPECIE (
        ID_ESPECIE INT PRIMARY KEY,
        NOME VARCHAR(50) NOT NULL
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_RACA' AND xtype='U')
BEGIN
    CREATE TABLE TB_RACA (
        ID_RACA INT PRIMARY KEY,
        NOME VARCHAR(100) NOT NULL,
        PORTE VARCHAR(10) NOT NULL CONSTRAINT CK_RACA_PORTE CHECK (PORTE IN ('PEQUENO','MEDIO','GRANDE')),
        ID_ESPECIE INT NOT NULL CONSTRAINT FK_RACA_ESPECIE REFERENCES TB_ESPECIE(ID_ESPECIE)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_PET' AND xtype='U')
BEGIN
    CREATE TABLE TB_PET (
        ID_PET INT PRIMARY KEY,
        NOME VARCHAR(50) NOT NULL,
        DT_NASCIMENTO DATE NOT NULL,
        SEXO CHAR(1) NOT NULL CONSTRAINT CK_PET_SEXO CHECK (SEXO IN ('M','F')),
        FOTO_URL VARCHAR(255) NOT NULL,
        ID_TUTOR INT NOT NULL CONSTRAINT FK_PET_TUTOR REFERENCES TB_TUTOR(ID_TUTOR),
        ID_RACA INT NOT NULL CONSTRAINT FK_PET_RACA REFERENCES TB_RACA(ID_RACA)
    );
END;

-- 4. CONSULTAS, PRONTUÁRIOS E PRESCRIÇÕES
IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_CONSULTA' AND xtype='U')
BEGIN
    CREATE TABLE TB_CONSULTA (
        ID_CONSULTA INT PRIMARY KEY,
        DATA_HORA DATETIME2 NOT NULL,
        MODALIDADE VARCHAR(15) NOT NULL CONSTRAINT CK_CONSULTA_MODALIDADE CHECK (MODALIDADE IN ('ONLINE','PRESENCIAL')),
        STATUS VARCHAR(15) NOT NULL CONSTRAINT CK_CONSULTA_STATUS CHECK (STATUS IN ('AGENDADA','REALIZADA','CANCELADA')),
        OBSERVACOES VARCHAR(1000),
        ID_PET INT NOT NULL CONSTRAINT FK_CONSULTA_PET REFERENCES TB_PET(ID_PET),
        ID_VETERINARIO INT NOT NULL CONSTRAINT FK_CONSULTA_VETERINARIO REFERENCES TB_VETERINARIO(ID_VETERINARIO)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_PRONTUARIO' AND xtype='U')
BEGIN
    CREATE TABLE TB_PRONTUARIO (
        ID_PRONTUARIO INT PRIMARY KEY,
        DIAGNOSTICO VARCHAR(500) NOT NULL,
        TRATAMENTO VARCHAR(500),
        SINTOMAS VARCHAR(250),
        PESO_ANIMAL DECIMAL(5,2),
        TEMPERATURA DECIMAL(4,1),
        EXAMES_SOLICITADOS VARCHAR(250),
        DATA_RETORNO DATE,
        ID_CONSULTA INT NOT NULL CONSTRAINT FK_PRONTUARIO_CONSULTA REFERENCES TB_CONSULTA(ID_CONSULTA)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_PRESCRICAO' AND xtype='U')
BEGIN
    CREATE TABLE TB_PRESCRICAO (
        ID_PRESCRICAO INT PRIMARY KEY,
        TIPO VARCHAR(15) NOT NULL CONSTRAINT CK_PRESCRICAO_TIPO CHECK (TIPO IN ('MEDICAMENTO', 'DIETA', 'RESTRICAO')),
        DESCRICAO VARCHAR(200) NOT NULL,
        POSOLOGIA VARCHAR(350),
        ID_PRONTUARIO INT NOT NULL CONSTRAINT FK_PRESCRICAO_PRONTUARIO REFERENCES TB_PRONTUARIO(ID_PRONTUARIO)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_HISTORICO_SAUDE' AND xtype='U')
