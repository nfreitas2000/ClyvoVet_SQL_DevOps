    CREATE TABLE TB_CIDADE (
        ID_CIDADE INT PRIMARY KEY,
        NOME VARCHAR(100) NOT NULL,
        ID_ESTADO INT NOT NULL CONSTRAINT FK_CIDADE_ESTADO REFERENCES TB_ESTADO(ID_ESTADO)
    );
END;

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='TB_BAIRRO' AND xtype='U')
